"""
llm_fallback.py — Few-shot Text-to-SQL fallback using Gemini 2.0 Flash.
Triggers only when deterministic handlers return 0.
"""
import os
import re
import sqlite3
import warnings
warnings.filterwarnings("ignore")

import google.generativeai as genai
from src.config import GEMINI_API_KEY, GEMINI_MODEL
from src.money import format_as_answer

SCHEMA_TEXT = """
Database Schema (SQLite):
1. clients(client_id INTEGER PRIMARY KEY, client_name TEXT)
2. engineers(engineer_id INTEGER PRIMARY KEY, name TEXT, designation TEXT, wage_group TEXT, total_experience INTEGER)
3. works(work_id INTEGER PRIMARY KEY, project_name TEXT, client_id INTEGER, contract_value INTEGER, completion_date TEXT, commencement_date TEXT, work_category TEXT, performance_grading TEXT, role TEXT, has_reference_letter INTEGER, has_performance_bond INTEGER)
4. engineer_works(engineer_id INTEGER, work_id INTEGER)
5. engineer_certs(engineer_id INTEGER, cert_type TEXT, cert_id TEXT, issue_date TEXT)
6. receivables(receivable_id INTEGER, invoice_no TEXT, client_name TEXT, client_id INTEGER, invoice_date TEXT, invoiced REAL, status TEXT, received REAL, outstanding REAL)
"""

FEW_SHOT_EXAMPLES = """
Few-Shot Examples:

Q: "Public Health Engineering Dept, Gujarat; as Prime — what's the contract value?"
SQL: SELECT SUM(contract_value) FROM works WHERE client_id = (SELECT client_id FROM clients WHERE LOWER(client_name) LIKE '%gujarat%') AND LOWER(role) LIKE '%prime%'

Q: "Chandan Banerjee's March 10, 2021 PMP to WTP Augmentation West Bengal Pkg-51 completion days?"
SQL: SELECT ABS(JULIANDAY(completion_date) - JULIANDAY('2021-03-10')) FROM works WHERE project_name LIKE '%Pkg-51%'

Q: "Suvarna Projects Limited; excluding water supply — what's the final tally?"
SQL: SELECT SUM(contract_value) FROM works WHERE client_id = (SELECT client_id FROM clients WHERE LOWER(client_name) LIKE '%suvarna%') AND LOWER(work_category) NOT LIKE '%water supply%'

Q: "Irrigation & Waterways Dept, Govt of Uttar Pradesh; Excellent — sum of contract amounts?"
SQL: SELECT SUM(contract_value) FROM works WHERE client_id = (SELECT client_id FROM clients WHERE LOWER(client_name) LIKE '%uttar pradesh%') AND LOWER(performance_grading) LIKE '%excellent%'

Q: "Jal Nigam, Jharkhand account; unbilled remainder after comparing awarded contract value against submitted claims?"
SQL: SELECT MAX(0, (SELECT SUM(contract_value) FROM works WHERE client_id = (SELECT client_id FROM clients WHERE LOWER(client_name) LIKE '%jharkhand%')) - (SELECT SUM(invoiced) FROM receivables WHERE client_id = (SELECT client_id FROM clients WHERE LOWER(client_name) LIKE '%jharkhand%')))
"""

def generate_sql_from_llm(question: str) -> str:
    """Query Gemini 2.0 Flash to translate ambiguous question to SQLite query."""
    if not GEMINI_API_KEY:
        print("[LLM Fallback Notice] GEMINI_API_KEY is empty/missing in environment or .env!")
        return None
    try:
        print(f"[LLM Fallback] Querying Gemini API for: {question[:55]}...")
        genai.configure(api_key=GEMINI_API_KEY)
        model = genai.GenerativeModel(GEMINI_MODEL)
        prompt = f"{SCHEMA_TEXT}\n{FEW_SHOT_EXAMPLES}\n\nTranslate the following question into a single executable SQLite query. Output ONLY the SQL query, nothing else.\n\nQ: \"{question}\"\nSQL:"
        response = model.generate_content(prompt)
        text = response.text.strip()
        sql_m = re.search(r'SELECT\s+.*', text, re.IGNORECASE | re.DOTALL)
        if sql_m:
            sql = sql_m.group(0).split('```')[0].strip()
            print(f"  -> Generated SQL: {sql}")
            return sql
    except Exception as e:
        print(f"  -> LLM Fallback API Error: {e}")
    return None


def execute_llm_fallback(conn: sqlite3.Connection, question: str) -> float:
    """Safely execute LLM-generated SQL query and validate returned answer."""
    sql = generate_sql_from_llm(question)
    if not sql:
        return 0
    
    clean_sql = sql.strip().upper()
    if not clean_sql.startswith("SELECT") or any(kw in clean_sql for kw in ["DROP", "DELETE", "INSERT", "UPDATE", "ALTER", "CREATE"]):
        print(f"  -> Rejected unsafe SQL generated by LLM: {sql}")
        return 0
        
    try:
        cur = conn.execute(sql)
        row = cur.fetchone()
        if row and row[0] is not None:
            ans = float(row[0])
            print(f"  -> Query Result: {ans}")
            return format_as_answer(ans)
    except sqlite3.Error as e:
        print(f"  -> Failed executing LLM SQL: {sql} | Error: {e}")
        
    return 0
